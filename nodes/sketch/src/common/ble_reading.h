#pragma once

// Compact binary form of a Reading carried in a BLE advertisement (no pairing, no
// connection). Used by a node as a fallback while WiFi is down; the alert server scans for
// it alongside UDP. Legacy advertising allows 31 bytes, so the reading travels as a single
// Manufacturer Specific Data AD structure:
//
//   [len][0xFF][company id LE (2)][payload (ble_payload_size)]
//
// Payload, little-endian:
//   0   1  header: 0xC0 magic | 0x08 time synchronized | 0x01 version
//   1   4  session nonce (session_id = "boot-<nonce>")
//   5   4  seq
//   9   4  dateObserved, Unix epoch seconds
//   13  2  temperature, centi-degrees Celsius (signed)
//   15  2  relative humidity, fraction x 10000 (0..10000)
//   17 10  node_id, ASCII, zero-padded
//
// Location is not carried; the receiver fills it in. QoS is always BestEffort (one-way).

#include "protocol.h"

#include <cstddef>
#include <cstdint>
#include <optional>
#include <string>
#include <string_view>

namespace common::ble {

/** @brief Bluetooth SIG company identifier reserved for testing. */
inline constexpr std::uint16_t company_id = 0xFFFF;
/** @brief Bytes of manufacturer data after the company identifier. */
inline constexpr std::size_t payload_size = 27;
/** @brief Longest node_id that fits in the payload. */
inline constexpr std::size_t max_node_id_size = 10;
/** @brief Prefix of the session ids generated by the nodes ("boot-<u32>"). */
inline constexpr std::string_view session_prefix = "boot-";

/**
 * @brief Encodes a reading into the advertisement payload (without the company id).
 * @return `std::nullopt` if the reading cannot be represented: node_id too long or not
 *         printable, session_id not "boot-<u32>", timestamp not "YYYY-MM-DDTHH:MM:SSZ",
 *         or temperature/humidity outside the encodable range.
 */
std::optional<std::string> encodeReading(const common::protocol::Reading& reading);

/**
 * @brief Decodes an advertisement payload (without the company id) into a Reading.
 * @return `std::nullopt` if the payload has the wrong size, magic or version.
 *         The location of the returned reading is (0, 0).
 */
std::optional<common::protocol::Reading> decodeReading(std::string_view payload);

}
